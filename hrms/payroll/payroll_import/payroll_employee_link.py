"""Match the payroll-template ID NUMBER to a Frappe Employee.

The Employee document name (HR-EMP-…) is generated by Frappe. The ID NUMBER
column on staff payroll and lumpsum Excel files is stored on Employee.employee_number.
"""

from __future__ import annotations

import re

import frappe
from frappe import _

from hrms.payroll.payroll_import.payroll_month_utils import normalize_employee_id_number


def compact_payroll_id(value: str | None) -> str:
	"""Compare key for an ID NUMBER: spacing ignored, and 080 matches 80."""
	compact = re.sub(r"\s+", "", normalize_employee_id_number(value)).lower()
	if compact.isdigit():
		compact = compact.lstrip("0") or "0"
	return compact


def sql_compact_payroll_id(column: str) -> str:
	"""SQL expression with the same rules as compact_payroll_id for a column name."""
	raw = f"REPLACE(LOWER(IFNULL({column}, '')), ' ', '')"
	stripped = f"TRIM(LEADING '0' FROM {raw})"
	return (
		f"CASE WHEN {raw} REGEXP '^[0-9]+$' "
		f"THEN IF({stripped} = '', '0', {stripped}) "
		f"ELSE {raw} END"
	)


def find_employee_for_payroll_id(employee_id: str | None) -> str | None:
	"""Return the Employee name for a payroll-template ID, ignoring spacing."""
	raw = (employee_id or "").strip()
	normalized = normalize_employee_id_number(raw)
	if not normalized:
		return None

	seen: set[str] = set()
	for candidate in (normalized, raw):
		if not candidate or candidate in seen:
			continue
		seen.add(candidate)
		name = frappe.db.get_value("Employee", {"employee_number": candidate}, "name")
		if name:
			return name

	compact = compact_payroll_id(normalized)
	if not compact:
		return None
	for row in frappe.get_all(
		"Employee",
		filters={"employee_number": ["is", "set"]},
		fields=["name", "employee_number"],
	):
		if compact_payroll_id(row.employee_number) == compact:
			return row.name
	return None


def payroll_id_variants(payroll_id: str | None) -> list[str]:
	"""Stored ID NUMBER values that mean the same payroll id (spacing ignored)."""
	normalized = normalize_employee_id_number(payroll_id)
	compact = compact_payroll_id(normalized)
	variants = {normalized} if normalized else set()
	if compact:
		variants.add(compact)
	if not compact:
		return [v for v in variants if v]
	rows = frappe.db.sql(
		f"""
		SELECT DISTINCT employee_id_number
		FROM `tabImported Payroll Record`
		WHERE docstatus < 2
			AND {sql_compact_payroll_id("employee_id_number")} = %s
		""",
		compact,
		pluck=True,
	)
	variants.update(row for row in rows if row)
	return [v for v in variants if v]


def link_imported_payroll_to_employee(employee: str, payroll_id: str | None) -> int:
	"""Attach staff payroll and lumpsum rows to this employee when the ID matches."""
	if not employee or not payroll_id:
		return 0
	compact = compact_payroll_id(payroll_id)
	if not compact:
		return 0
	rows = frappe.db.sql(
		f"""
		SELECT name, employee
		FROM `tabImported Payroll Record`
		WHERE docstatus < 2
			AND {sql_compact_payroll_id("employee_id_number")} = %s
		""",
		compact,
		as_dict=True,
	)
	updated = 0
	for row in rows:
		if row.employee == employee:
			continue
		frappe.db.set_value(
			"Imported Payroll Record",
			row.name,
			"employee",
			employee,
			update_modified=False,
		)
		updated += 1
	return updated


def validate_unique_payroll_id(doc, method=None):
	payroll_id = normalize_employee_id_number(doc.employee_number)
	if payroll_id:
		doc.employee_number = payroll_id
	else:
		return
	other = find_employee_for_payroll_id(payroll_id)
	if other and other != doc.name:
		other_name = frappe.db.get_value("Employee", other, "employee_name") or other
		frappe.throw(
			_("Employee Number {0} is already used by {1} ({2}).").format(payroll_id, other_name, other)
		)


def on_employee_payroll_id_update(doc, method=None):
	previous = doc.get_doc_before_save()
	old = normalize_employee_id_number(getattr(previous, "employee_number", None) if previous else None)
	new = normalize_employee_id_number(doc.employee_number)
	if not new or new == old:
		return
	link_imported_payroll_to_employee(doc.name, new)
